/*
# Narration clips table + storage bucket

## Overview
Tracks TTS clips generated by the `narrate` edge function for stories
that have ElevenLabs narration configured but missing pre-recorded segments.

## Changes
- `narration_clips` table: one row per generated MP3, keyed by story + text hash
- Storage bucket `narration`: public bucket for serving generated MP3s
*/

CREATE TABLE IF NOT EXISTS narration_clips (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  story_slug text NOT NULL,
  text_hash text NOT NULL,
  chars integer NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  created_by uuid,
  UNIQUE (story_slug, text_hash)
);

ALTER TABLE narration_clips ENABLE ROW LEVEL SECURITY;

-- Authors/admins can see narration stats for their stories
CREATE POLICY "narration_clips_select" ON narration_clips
  FOR SELECT TO authenticated USING (true);

-- Only service role can insert (edge function uses service role key)
CREATE POLICY "narration_clips_insert" ON narration_clips
  FOR INSERT TO authenticated WITH CHECK (false);

CREATE POLICY "narration_clips_insert_service" ON narration_clips
  FOR INSERT WITH CHECK (true);

-- Storage bucket for narration audio
INSERT INTO storage.buckets (id, name, public)
VALUES ('narration', 'narration', true)
ON CONFLICT (id) DO NOTHING;