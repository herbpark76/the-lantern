### 1

In the winter solstice month of 1961, the cold of Daegu pooled in the mountain-ringed basin and did not know how to leave. When the wind came down off Palgongsan and scoured the dry bed of the Sincheon, the roofs of the shanties below the embankment lifted all at once. Many who had fled south during the war and simply stayed lived under that embankment. Eight years had passed since the fighting ended, but for them the war had not ended; only the gunfire had stopped. Over the walls of the American base to the south drifted a smell of rich cooking, and on this side of the wall people joked that the smell alone could fill your belly.

That May, a rumor reached the farthest Daegu alley: soldiers in Seoul had turned the country over. Grown-ups lowered their voices before the radio; in the tearooms, men behind open newspapers watched one another. Whoever ruled the nation, radishes at Seomun Market cost the same, and a coal briquette cost a little more. For the poor, the world turning over usually amounted to about that much.

But for the children of the national school, the world was still no bigger than the cart outside the gate.

The cart was there before the last bell. On one side the chrysanthemum-cake molds flipped, clack-clack, clack-clack; on the other, slices of white bread drank oil on a griddle. Bread that had found its way out of the American base by some road no one asked about. The vendor wore a dyed army uniform, and the children simply called him Mister. He swiped on a red jam as thin as water and turned each slice face-down onto oil cooked nearly black. At the hiss and the smell of sugar, the children swallowed ahead of time.

"Mister, give us one."

"Money first, I said. You got money?"

"I'll pay tomorrow."

"Then come eat tomorrow, you little leper."

The children roared. The boy who had been teased sniffed and glared at the laughing ones, but in the end he laughed too. Poor children's laughter was like that: the one being laughed at hurt less if he laughed along.

Jung-won, daughter of the Huh house, stood about three steps back from the cart. In her coat pocket a few coins had gone warm with the sweat of her palm. Her allowance from Mother. If she had meant to buy, she would have bought already. She only watched the bread turn over. Top going to the bottom, bottom coming to the top. Today, for some reason, it caught in her eye.

At the very back of the crowd stood Sun-bun, hands folded into her sleeves, peering at the griddle as solemnly as someone buying bread she would never buy. The tip of her nose was red with cold, and on her feet were a boy's rubber shoes, handed down from who knows whom, the toes a hand's width too long.

### 2

That morning, report cards had come out.

Through third grade, music had always been Jung-won's. Solfège and theory never stumped her, and when she sang, even the children fooling around in the back row lifted their heads. But in fourth grade the homeroom teacher changed. The new one was a young man with clean fingernails who always spoke to the children about fairness.

That year Hye-suk was in the class, a doctor's daughter. She had gentle, smiling eyes, and when she borrowed someone's eraser she always brushed it clean before giving it back. Hye-suk had done nothing wrong. It was only that the children had seen her mother, more than once, carry a wrapped bundle into the teachers' room in a velvet coat. No one knew what was in the bundle. Not knowing told them everything. In the schools of Daegu in those days a bundle traveled faster than words, and a teacher's brush tended to lean toward wherever a bundle had been set down. Few grown-ups blamed anyone for it. Everyone lived that way, and they called living that way the world.

In the music column of the report card was written: 2.

Jung-won looked down at that number for a long time. If she could have hated Hye-suk it would have been easier. With no one to hate, the hurt had nowhere to go. From somewhere inside rose words she had never heard herself say.

What a filthy world, this is.

They were words too early for a ten-year-old girl. But once she knew them she could never un-know them. Perhaps a whole human life is just this: living on without ever erasing the few words one learned first.

### 3

The Huh house had a big gate. Inside it, even in winter, not a single broom stroke in the yard was out of place. Jung-won's mother had graduated from Daegu Girls' High under the Japanese, a New Woman, and without ever once saying so she made sure the household never forgot it. The place of the soy-sauce dish on the table, the angle at which the folding screen opened, the collar band of a jeogori in the wardrobe: nothing escaped her eye. For feasts she had yugwa and yakgwa made to order in Gyeongju. To send all the way to Gyeongju for what Daegu also sold: that was what Mother said to the world.

Mother glanced over the report card once and folded it.

"Second is fine."

Her brother's report card she read twice. Once with her eyes, once aloud.

"Mother, the teacher — Hye-suk's mother, she —"

"What's a girl going to do with first place in singing? Go wash your hands."

That was the end of it. The idea that a daughter is another family's person once she is married off had never been erased from that educated head. Perhaps it was not that it could not be erased, but that she never meant to erase it. Mother never cursed, and never said she was sorry. That day, dimly, Jung-won understood for the first time that the two grew from one root.

In the kitchen Cheongdo-daek was crouched before the fire hole. She had married at sixteen, lost her husband within two years, been turned away by her own family, and gone from kitchen to kitchen until she came to the Huh house; this was her sixth year. No one in that house knew her name. Mother, so sweet to her friends, had never called her anything but "you there" or "hey."

Cheongdo-daek pulled Jung-won's chapped hands close to the fire and slipped her a sweet potato she had buried in the embers.

"Something happen, miss?"

"I came second in singing."

Cheongdo-daek poked the fire once with the fire stick and snorted.

"If our Won-i came second, then first was stolen. I know it all. That's how the world goes. The bitch with the bundle comes first."

"Ajimae, they said we mustn't say 'bitch.'"

"In the kitchen you can. The mistress's ears don't reach here."

Jung-won snorted a laugh around the sweet potato. Whether it began that day or earlier, from then on, whenever the grown-ups gathered in the main hall to lay out their boasts, Jung-won was always somewhere near the kitchen.

### 4

On the evening of the solstice, Aunt came.

Aunt was Mother's next-younger sister, and so unlike her it was hard to believe they came from one womb. She was plainer than Mother and had never set foot inside a girls' high school, but when Aunt walked in, the very air of the house changed. Uncle ran a textile mill or some kind of factory in Daegu, and they lived in a hanok so big the Huh house couldn't hold a candle to it. Yet whenever Aunt threw a feast in that big house she fed them all: the mill workers, the market people, even the neighborhood beggars. Mother called it wasteful.

Aunt came through the gate with a jar of red-bean porridge on her head.

"Won-a, Won-a! Where's our Won-i got to? Your aunt picked out the biggest rice balls for you!"

When Jung-won ran out of the kitchen, Aunt took her face in both hands before she had even set the jar down. Aunt's hands were cold, and strangely warm.

"Why the long face?"

Cheongdo-daek told on the report card over the hearth. Aunt's eyes went round.

"What? He heard our Won-i sing and gave her second? That so-called teacher — are his eyeballs crooked or are his earholes plugged? I hope he eats what's in that bundle and gets the runs, the leper. Tomorrow I'll go down to that school and put the bundle over his head for him."

Cheongdo-daek burst first. Her brother laughed, and so did the uncle's wife listening from the main hall. Jung-won laughed too. Aunt's curses were not the kind that stab. They were the kind that scratch where it itches. So when Aunt cursed, everyone laughed.

Only Mother did not.

"Sister, mind your words in front of the child."

"Mind what? The child says she was wronged. You have to call a wrong a wrong, or the child gets sick inside."

Instead of answering, Mother jerked her chin at Cheongdo-daek to carry the porridge into the kitchen. That night Jung-won ate two bowls of the porridge Aunt ladled out. Every time she counted the rice balls, Aunt's words circled on the tip of her tongue: call a wrong a wrong, or you get sick inside. Jung-won thought it truer than anything Mother had ever said. And it frightened her a little to think so.

### 5

Two days later, Jung-won emptied her allowance.

"Mister, two. Wrap them in newspaper."

"Two? Going to eat both yourself?"

She didn't answer. Held against her chest, the oil-soaked newspaper was almost warm.

Sun-bun's house stood beside a ditch below the Sincheon embankment. Under a wall of patched boards, ditch water had frozen mid-flow, and even in the solstice cold the smell did not freeze with it. Jung-won had never forgotten the first day she came: so people live in places like this. It was less surprise than the feeling of having caught out, all alone, a secret the grown-ups had hidden away. The secret was that the house with the big gate and the house with board walls stood under the same sky.

The door was open. Thieves don't bother poor houses, people in that neighborhood said. A house with nothing to steal had no reason to shut its door.

Jung-won set the bundle on the cooking hearth, took the stub of a pencil from her pencil case, and tore a corner from her notebook. Her fingers were stiff, and the letters came out crooked.

One for your mom and one for you. Eat up.

She did not write her name.

### 6

At the mouth of Seomun Market, among the women who had spread their wrapping cloths on the cold ground, sat Sun-bun's mother. A ragged scarf was wound up to her ears, and before her lay a few bundles of dried radish greens and a handful of dried fern. All morning she had sold two bundles. When she breathed on the cracked backs of her hands, the breath bloomed white and was gone.

At the mouth of an alley a little way off, she saw a girl stop. A girl in a fine-colored coat and a knitted scarf. Isn't that the Huh girl? Sun-bun's school friend, she said. What would a child from that house want in this market. The girl seemed to stare this way a long while, then, before their eyes could meet, wheeled around and vanished down a side alley. Sun-bun's mother did not know what it meant. Children of houses that had things usually turned away like that from grown-ups of houses that had nothing, so she thought no more of it.

That night Sun-bun found the newspaper bundle on the hearth. The oil had soaked through and blurred all the print.

"Mom, look. There's a note. It says, 'One for your mom and one for you. Eat up.'"

"Who left it?"

"Don't know. There's no name."

For a long while Sun-bun's mother said nothing. The knitted scarf wheeling away at the alley's mouth rose before her eyes. Only now did she think she understood why the girl had turned away: so the one receiving would not have to say thank you. That a ten-year-old knew such a thing made Sun-bun's mother feel sorrow before she felt grateful.

"…Let's eat. Cold, but let's eat."

The bread had gone cold. The jam was thin as water and the oil smelled stale. Mother and daughter each took a piece and ate it very slowly.

### 7

At that hour Jung-won stood before the big gate of the Huh house. The way home had been cold but strangely light. Something went off in her chest like the sound at her grandmother's house in Uiseong on school holidays, when she pushed straw into the fire hole and it crackled ttadadadadada.

The world was filthy. But like the bread on the cart, even a filthy thing could be turned over once in a while. Ten-year-old Jung-won could not have put it into words. Only her body knew. And what the body learns first outlasts what the head learns.

### 8

Sixty-five years later, in a living room in Dallas, Texas, Jung-won Huh remembered that note again. It was an autumn night not long after she had come home from the hospital. Sophie lay at her feet.

"How strange," she said. "It's coming back to me."
